export const buildExamCopyData = (source, examName, createdBy) => ({
  examName: examName.trim(),
  academicYear: source.academicYear,
  examType: source.examType,
  classSelectionMode: source.classSelectionMode,
  applicableClasses: [...source.applicableClasses],
  classExamConfigs: source.classExamConfigs.map((config) => ({
    className: config.className,
    subjectSelectionMode: config.subjectSelectionMode,
    subjects: config.subjects.map((subject) => ({
      subjectName: subject.subjectName,
      fullMarks: subject.fullMarks,
      passMarks: subject.passMarks,
      theoryFullMarks: subject.theoryFullMarks,
      theoryPassMarks: subject.theoryPassMarks,
      practicalFullMarks: subject.practicalFullMarks,
      practicalPassMarks: subject.practicalPassMarks,
      creditHour: subject.creditHour,
      practicalCreditHour: subject.practicalCreditHour,
      hasPractical: subject.hasPractical,
    })),
    targetStudentsMode: config.targetStudentsMode,
    selectedStudents: [...config.selectedStudents],
  })),
  startDate: source.startDate,
  endDate: source.endDate,
  marksEntryLastDate: source.marksEntryLastDate,
  resultPublishDate: source.resultPublishDate,
  isFinalExam: false,
  isResultPublished: false,
  status: "draft",
  description: source.description,
  createdBy,
});
